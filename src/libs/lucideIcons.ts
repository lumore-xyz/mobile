const toLucideIconName = (name: string) =>
  name
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Za-z])([0-9])/g, (_match, letter, digit) =>
      letter === "x" ? `${letter}${digit}` : `${letter}-${digit}`,
    )
    .replace(/([0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();

